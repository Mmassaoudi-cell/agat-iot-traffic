    Xt = torch.FloatTensor(X_tr)
    Xe = torch.FloatTensor(X_te)
    yt = torch.LongTensor(y_tr)
    ye = torch.LongTensor(y_te)
    d, c = X_tr.shape[1], len(class_names)

    # ── 2. Train AGAT Hybrid CE ────────────────────────────────────────────────
    print("\n[2] Training AGAT Hybrid CE...")
    model_agat = BaseDNN(d, c)
    train_agat_hybrid_ce(
        model_agat, Xt, yt, eps=EPS, alpha=ALPHA_TRAIN, iters=T_TRAIN,
        epochs=EPOCHS, feat_mask=feat_mask, device=DEVICE, verbose=True,
    )

    # ── 3. Train PGD-AT baseline ───────────────────────────────────────────────
    print("\n[3] Training PGD-AT baseline...")
    model_pgd = BaseDNN(d, c)
    class_w   = compute_class_weights(y_tr, DEVICE)
    opt_pgd   = optim.AdamW(model_pgd.parameters(), lr=1e-3, weight_decay=5e-4)
    sched_pgd = optim.lr_scheduler.CosineAnnealingWarmRestarts(opt_pgd, T_0=10, T_mult=2)
    loader_pgd = DataLoader(TensorDataset(Xt.to(DEVICE), yt.to(DEVICE)),
                            batch_size=BATCH, shuffle=True)
    model_pgd = model_pgd.to(DEVICE)
    for ep in range(1, EPOCHS + 1):
        model_pgd.train()
        for xb, yb in loader_pgd:
            opt_pgd.zero_grad()
            alpha = EPS / max(T_TRAIN / 2.0, 1.0)
            xa    = pgd(model_pgd, xb, yb, EPS, alpha, T_TRAIN, class_w)
            model_pgd.train()
            lc = F.cross_entropy(model_pgd(xb), yb, weight=class_w)
            la = F.cross_entropy(model_pgd(xa), yb, weight=class_w)
            (0.5 * lc + 0.5 * la).backward()
            opt_pgd.step()
        sched_pgd.step()
        if ep % 5 == 0 or ep == EPOCHS:
            print(f"  PGD-AT  epoch {ep:3d}/{EPOCHS}")

    # ── 4. Evaluate ───────────────────────────────────────────────────────────
    print("\n[4] Evaluating...")
    for tag, mdl in [("AGAT Hybrid CE", model_agat), ("PGD-AT", model_pgd)]:
        clean  = evaluate_clean(mdl, Xe, ye, DEVICE)
        adv    = evaluate_adversarial(mdl, Xe, ye, EPS, feat_mask, DEVICE)
        pc_f1  = per_class_f1(mdl, Xe, ye, class_names, EPS, DEVICE)
        print(f"\n  {tag}")
        print(f"    Clean:     acc={clean['acc']*100:.1f}%  f1={clean['f1']:.3f}  "
              f"auc={clean['auc']:.4f}")
        print(f"    FGSM:      {adv['fgsm']*100:.1f}%")
        print(f"    PGD-10:    {adv['pgd_10']*100:.1f}%")
        print(f"    PGD-20:    {adv['pgd_20']*100:.1f}%")
        print(f"    PGD-50:    {adv['pgd_50']*100:.1f}%")
        print(f"    BI-PGD:    {adv['bi_pgd']*100:.1f}%   ← stress-test metric")
        print(f"    Rand-AGAT: {adv['rand_agat']*100:.1f}%")
        print(f"    Per-class F1 (PGD-10):")
        for cn, v in pc_f1.items():
            print(f"      {cn}: {v:.3f}")

    # ── 5. McNemar test ───────────────────────────────────────────────────────
    print("\n[5] McNemar test (AGAT Hybrid CE vs PGD-AT, PGD-10)...")
    preds_agat, y_true = _adv_preds(model_agat, Xe, ye, EPS, DEVICE)
    preds_pgd,  _      = _adv_preds(model_pgd,  Xe, ye, EPS, DEVICE)
    mcn_p, mcn_chi2    = mcnemar_test(y_true, preds_agat, preds_pgd)
    print(f"  chi2={mcn_chi2:.3f}  p={'<0.001' if mcn_p < 0.001 else f'{mcn_p:.4f}'}"
          f"  {'SIGNIFICANT' if mcn_p < 0.05 else 'not significant'}")

    # ── 6. Save results ───────────────────────────────────────────────────────
    if save_json:
        clean_agat = evaluate_clean(model_agat, Xe, ye, DEVICE)
        clean_pgd  = evaluate_clean(model_pgd,  Xe, ye, DEVICE)
        adv_agat   = evaluate_adversarial(model_agat, Xe, ye, EPS, feat_mask, DEVICE)
        adv_pgd    = evaluate_adversarial(model_pgd,  Xe, ye, EPS, feat_mask, DEVICE)
        out = {
            "AGAT Hybrid CE": {
                "clean": {k: round(float(v), 4) for k, v in clean_agat.items()},
                "adv":   {k: round(float(v), 4) for k, v in adv_agat.items()},
            },
            "PGD-AT": {
                "clean": {k: round(float(v), 4) for k, v in clean_pgd.items()},
                "adv":   {k: round(float(v), 4) for k, v in adv_pgd.items()},
            },
            "mcnemar": {"chi2": round(mcn_chi2, 4), "p": round(mcn_p, 6)},
            "class_names": class_names,
            "hyperparameters": {
                "eps": EPS, "alpha_train": ALPHA_TRAIN, "T_train": T_TRAIN,
                "epochs": EPOCHS, "batch": BATCH, "momentum_attr": MOMENTUM_ATTR,
                "n_per_class": N_PER_CLASS, "seed": SEED,
                "loss_weights": {"clean": 0.30, "agat": 0.50, "pgd": 0.20},
            },
        }
        out_path = os.path.join(results_dir, "agat_hybrid_ce_results.json")
        with open(out_path, "w") as f:
            json.dump(out, f, indent=2)
        print(f"\n  Results saved to {out_path}")

    print(f"\n  Total time: {(time.time() - t0) / 60:.1f} min")
    return model_agat, model_pgd


