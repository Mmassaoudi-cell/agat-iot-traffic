EVAL_CAP = 1000   # cap evaluation to speed up (use all samples for final eval)


@torch.no_grad()
def evaluate_clean(model, X_te, y_te, device=DEVICE):
    """Accuracy, macro-F1, macro-AUC on clean test set."""
    model.eval()
    Xe = X_te.to(device)
    logits = model(Xe)
    preds  = logits.argmax(1).cpu().numpy()
    y_np   = y_te.numpy()
    n_cls  = len(np.unique(y_np))
    acc    = accuracy_score(y_np, preds)
    f1     = f1_score(y_np, preds, average="macro", zero_division=0)
    try:
        probs = F.softmax(logits, 1).cpu().numpy()
        auc   = roc_auc_score(y_np, probs, multi_class="ovr", average="macro")
    except Exception:
        auc = float("nan")
    return dict(acc=acc, f1=f1, auc=auc)


def _adv_accuracy(attack_fn, model, X_te, y_te, device=DEVICE, cap=EVAL_CAP):
    """Evaluate adversarial accuracy using a given attack function."""
    Xe = X_te[:cap].to(device)
    ye = y_te[:cap].to(device)
    preds_all = []
    for i in range(0, len(Xe), 256):
        model.train()                           # needed for BN in attack backward
        xa = attack_fn(Xe[i:i+256], ye[i:i+256])
        model.eval()
        with torch.no_grad():
            preds_all.append(model(xa).argmax(1).cpu())
    preds = torch.cat(preds_all).numpy()
    return accuracy_score(ye.cpu().numpy()[:len(preds)], preds)


def evaluate_adversarial(model, X_te, y_te,
                          eps=EPS, feat_mask=None,
                          device=DEVICE, cap=EVAL_CAP):
    """
    Full adversarial evaluation suite:
      FGSM, PGD-10, PGD-20, PGD-50, BI-PGD-10, Rand-AGAT-10
    """
    alpha10 = eps / 10.0
    alpha20 = eps / 20.0
    alpha50 = eps / 50.0

    return {
        "fgsm":      _adv_accuracy(
                         lambda x, y: fgsm(model, x, y, eps),
                         model, X_te, y_te, device, cap),
        "pgd_10":    _adv_accuracy(
                         lambda x, y: pgd(model, x, y, eps, alpha10, 10),
                         model, X_te, y_te, device, cap),
        "pgd_20":    _adv_accuracy(
                         lambda x, y: pgd(model, x, y, eps, alpha20, 20),
                         model, X_te, y_te, device, cap),
        "pgd_50":    _adv_accuracy(
                         lambda x, y: pgd(model, x, y, eps, alpha50, 50),
                         model, X_te, y_te, device, cap),
        "bi_pgd":    _adv_accuracy(
                         lambda x, y: bipgd(model, x, y, eps, alpha10, 10),
                         model, X_te, y_te, device, cap),
        "rand_agat": _adv_accuracy(
                         lambda x, y: random_agat(model, x, y, eps, alpha10, 10,
                                                   feat_mask=feat_mask),
                         model, X_te, y_te, device, cap),
    }


def per_class_f1(model, X_te, y_te, class_names,
                 eps=EPS, device=DEVICE, cap=EVAL_CAP):
    """Per-class F1 under PGD-10."""
    alpha = eps / 10.0
    Xe = X_te[:cap].to(device)
    ye = y_te[:cap].to(device)
    preds_all = []
    for i in range(0, len(Xe), 256):
        model.train()
        xa = pgd(model, Xe[i:i+256], ye[i:i+256], eps, alpha, 10)
        model.eval()
        with torch.no_grad():
            preds_all.append(model(xa).argmax(1).cpu())
    preds = torch.cat(preds_all).numpy()
    y_np  = ye.cpu().numpy()[:len(preds)]
    rpt   = classification_report(y_np, preds, output_dict=True, zero_division=0)
    return {cn: rpt.get(str(i), {}).get("f1-score", 0.0)
            for i, cn in enumerate(class_names)}


