def mcnemar_test(y_true, preds_a, preds_b):
    """
    McNemar's test between two classifiers.
    Returns (p_value, chi2_statistic).
    """
    a_right = np.array(preds_a) == np.array(y_true)
    b_right = np.array(preds_b) == np.array(y_true)
    b = np.sum(a_right  & ~b_right)
    c = np.sum(~a_right &  b_right)
    if b + c == 0:
        return 1.0, 0.0
    stat  = (abs(b - c) - 1.0) ** 2 / (b + c)
    p_val = 1.0 - scipy_chi2.cdf(stat, df=1)
    return float(p_val), float(stat)


def _adv_preds(model, X_te, y_te, eps=EPS, device=DEVICE, cap=EVAL_CAP):
    """Return adversarial predictions under PGD-10 (for McNemar test)."""
    alpha = eps / 10.0
    Xe = X_te[:cap].to(device)
    ye = y_te[:cap].to(device)
    preds = []
    for i in range(0, len(Xe), 256):
        model.train()
        xa = pgd(model, Xe[i:i+256], ye[i:i+256], eps, alpha, 10)
        model.eval()
        with torch.no_grad():
            preds.append(model(xa).argmax(1).cpu())
    return torch.cat(preds).numpy(), ye.cpu().numpy()[:sum(p.shape[0] for p in preds)]


