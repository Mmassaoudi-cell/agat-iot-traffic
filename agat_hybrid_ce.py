class ResBlock(nn.Module):
    """Two-layer residual block with BatchNorm."""
    def __init__(self, dim: int):
        super().__init__()
        self.block = nn.Sequential(
            nn.Linear(dim, dim), nn.BatchNorm1d(dim), nn.ReLU(),
            nn.Linear(dim, dim), nn.BatchNorm1d(dim),
        )
        self.relu = nn.ReLU()

    def forward(self, x):
        return self.relu(x + self.block(x))


class BaseDNN(nn.Module):
    """
    Residual MLP: Input → 512 → 256 → 128 → 64 → C classes.
    Used for all AGAT/TRADES variants.
    """
    def __init__(self, in_features: int, n_classes: int):
        super().__init__()
        self.proj = nn.Sequential(
            nn.Linear(in_features, 512), nn.BatchNorm1d(512), nn.ReLU(),
            nn.Dropout(0.25),
        )
        self.res1 = ResBlock(512)
        self.mid1 = nn.Sequential(
            nn.Linear(512, 256), nn.BatchNorm1d(256), nn.ReLU(), nn.Dropout(0.25),
        )
        self.res2 = ResBlock(256)
        self.mid2 = nn.Sequential(
            nn.Linear(256, 128), nn.BatchNorm1d(128), nn.ReLU(), nn.Dropout(0.25),
        )
        self.res3 = ResBlock(128)
        self.head = nn.Sequential(
            nn.Linear(128, 64), nn.ReLU(), nn.Dropout(0.2),
            nn.Linear(64, n_classes),
        )

    def forward(self, x):
        h = self.proj(x)
        h = self.res1(h)
        h = self.mid1(h)
        h = self.res2(h)
        h = self.mid2(h)
        h = self.res3(h)
        return self.head(h)


# ══════════════════════════════════════════════════════════════════════════════
# ADVERSARIAL ATTACKS
# ══════════════════════════════════════════════════════════════════════════════

def _ce_loss(model, x, y, class_w=None):
    """Weighted cross-entropy helper."""
    return F.cross_entropy(model(x), y, weight=class_w)


def fgsm(model, x, y, eps, class_w=None):
    """Fast Gradient Sign Method (single step)."""
    xr = x.clone().detach().requires_grad_(True)
    _ce_loss(model, xr, y, class_w).backward()
    model.zero_grad()
    return (x + eps * xr.grad.sign()).detach()


def pgd(model, x, y, eps, alpha, iters, class_w=None):
    """Projected Gradient Descent adversarial attack."""
    xa = x.clone().detach() + torch.zeros_like(x).uniform_(-eps / 2, eps / 2)
    for _ in range(iters):
        xa.requires_grad_(True)
        _ce_loss(model, xa, y, class_w).backward()
        model.zero_grad()
        xa = (xa + alpha * xa.grad.sign()).detach()
        xa = torch.max(torch.min(xa, x + eps), x - eps).detach()
    return xa


def agat_attack(model, x, y, eps, alpha, iters,
                feat_mask=None, momentum=MOMENTUM_ATTR, class_w=None):
    """
    AGAT attack: Momentum-attribution-guided PGD with L1-normalised
    budget redistribution.

    Algorithm:
      1. EMA-smooth the input×gradient attribution over PGD steps.
      2. L1-normalise: weights sum to 1 (pure redistribution).
      3. Step size = alpha * F_dim * w * sign(grad)  →  same mean magnitude as PGD.
      4. Project back onto the L-inf epsilon-ball.
    """
    xa = x.clone().detach() + torch.zeros_like(x).uniform_(-eps / 2, eps / 2)
    F_dim = x.shape[1]
    mask_t = torch.FloatTensor(feat_mask).to(x.device) if feat_mask is not None else None
    phi_ema = None

    for _ in range(iters):
        xa = xa.clone().detach().requires_grad_(True)
        _ce_loss(model, xa, y, class_w).backward()
        model.zero_grad()

        with torch.no_grad():
            grad = xa.grad.detach()
            phi  = (xa.detach() * grad).abs()          # input × gradient

            if mask_t is not None:
                phi = phi * mask_t.unsqueeze(0)         # zero non-perturbable dims

            # Momentum EMA
            phi_ema = phi if phi_ema is None else (
                momentum * phi_ema + (1.0 - momentum) * phi
            )

            # L1 normalisation (redistribute budget, same total magnitude as PGD)
            w    = phi_ema / (phi_ema.sum(dim=1, keepdim=True) + 1e-8)
            step = alpha * F_dim * w * grad.sign()

            xa = torch.max(torch.min(xa.detach() + step, x + eps), x - eps)

    return xa.detach()


def bipgd(model, x, y, eps, alpha, iters, class_w=None):
    """
    Boundary-Initialized PGD (BI-PGD): starts from a random point
    on the boundary of the L-inf epsilon-ball, then runs standard PGD.
    Stress-tests against gradient masking.
    """
    n  = torch.randn_like(x)
    xa = torch.max(torch.min(x + eps * n.sign(), x + eps), x - eps).detach()
    for _ in range(iters):
        xa.requires_grad_(True)
        _ce_loss(model, xa, y, class_w).backward()
        model.zero_grad()
        xa = (xa + alpha * xa.grad.sign()).detach()
        xa = torch.max(torch.min(xa, x + eps), x - eps).detach()
    return xa


def random_agat(model, x, y, eps, alpha, iters, feat_mask=None, class_w=None):
    """
    Random-AGAT ablation: replaces attribution weights with Dirichlet-random
    weights. Used to isolate attribution-specific contribution vs. any
    non-uniform budget redistribution effect.
    """
    xa = x.clone().detach() + torch.zeros_like(x).uniform_(-eps / 2, eps / 2)
    F_dim   = x.shape[1]
    mask_t  = torch.FloatTensor(feat_mask).to(x.device) if feat_mask is not None else None

    for _ in range(iters):
        xa = xa.clone().detach().requires_grad_(True)
        _ce_loss(model, xa, y, class_w).backward()
        model.zero_grad()

        with torch.no_grad():
            grad   = xa.grad.detach()
            w_rand = torch.from_numpy(
                np.random.dirichlet(np.ones(F_dim), x.shape[0]).astype(np.float32)
            ).to(x.device)
            if mask_t is not None:
                w_rand = w_rand * mask_t.unsqueeze(0)
                w_rand = w_rand / (w_rand.sum(dim=1, keepdim=True) + 1e-8)
            step = alpha * F_dim * w_rand * grad.sign()
            xa   = torch.max(torch.min(xa.detach() + step, x + eps), x - eps)

    return xa.detach()


# ══════════════════════════════════════════════════════════════════════════════
# CLASS WEIGHTS (inverse-frequency)
# ══════════════════════════════════════════════════════════════════════════════

def compute_class_weights(y_train, device=DEVICE):
    """Inverse-frequency class weights for imbalanced training data."""
    counts = np.bincount(y_train)
    w = 1.0 / (counts + 1e-6)
    w = w / w.sum() * len(counts)
    return torch.FloatTensor(w).to(device)


# ══════════════════════════════════════════════════════════════════════════════
# TRAINING — AGAT HYBRID CE
# ══════════════════════════════════════════════════════════════════════════════

def train_agat_hybrid_ce(
    model, X_tr, y_tr,
    eps=EPS, alpha=ALPHA_TRAIN, iters=T_TRAIN,
    epochs=EPOCHS, feat_mask=None,
    device=DEVICE, verbose=True,
):
    """
    Train AGAT Hybrid CE.

    Loss = 0.30 * CE(f(x), y)               [clean]
         + 0.50 * CE(f(x_agat), y)          [AGAT adversarial, attribution-guided]
         + 0.20 * CE(f(x_pgd),  y)          [PGD adversarial, generic L-inf]

    All CE terms use inverse-frequency class weights.

    Args:
        model      : BaseDNN (or any nn.Module with appropriate in/out dims)
        X_tr, y_tr : Training tensors
        eps        : L-inf perturbation budget (default 0.1)
        alpha      : PGD step size (default 0.04 = eps/2.5)
        iters      : PGD inner-loop steps (default 7)
        epochs     : Number of training epochs (default 30)
        feat_mask  : Per-feature perturbability mask array (83-dim for RT-IoT2022)
        device     : torch.device
        verbose    : Print epoch-level progress

    Returns:
        (clean_loss_history, adv_loss_history)
    """
    model = model.to(device)
    X_tr_d = X_tr.to(device)
    y_tr_d = y_tr.to(device)

    class_w = compute_class_weights(y_tr.numpy(), device)
    opt     = optim.AdamW(model.parameters(), lr=1e-3, weight_decay=5e-4)
    sched   = optim.lr_scheduler.CosineAnnealingWarmRestarts(opt, T_0=10, T_mult=2)
    loader  = DataLoader(TensorDataset(X_tr_d, y_tr_d), batch_size=BATCH, shuffle=True)

    hist_clean, hist_adv = [], []

    for ep in range(1, epochs + 1):
        model.train()
        lc_sum = la_sum = 0.0

        for xb, yb in loader:
            opt.zero_grad()

            # Clean loss
            lc = F.cross_entropy(model(xb), yb, weight=class_w)

            # AGAT adversarial examples (momentum attribution, L1-normalised)
            xa_agat = agat_attack(
                model, xb, yb, eps, alpha, iters,
                feat_mask=feat_mask, class_w=class_w,
            )

            # PGD adversarial examples (standard L-inf PGD)
            xa_pgd = pgd(model, xb, yb, eps, alpha, iters, class_w)

            model.train()
            la_agat = F.cross_entropy(model(xa_agat), yb, weight=class_w)
            la_pgd  = F.cross_entropy(model(xa_pgd),  yb, weight=class_w)

            # AGAT Hybrid CE loss
            loss = 0.30 * lc + 0.50 * la_agat + 0.20 * la_pgd
            loss.backward()
            opt.step()

            lc_sum += lc.item()
            la_sum += la_agat.item()

        sched.step()
        hist_clean.append(lc_sum / len(loader))
        hist_adv.append(la_sum / len(loader))

        if verbose and (ep % 5 == 0 or ep == 1 or ep == epochs):
            print(f"  Epoch {ep:3d}/{epochs}  clean_loss={hist_clean[-1]:.4f}  "
                  f"adv_loss={hist_adv[-1]:.4f}")

    return hist_clean, hist_adv


