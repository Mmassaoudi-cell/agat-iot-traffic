def stratified_subsample(X, y, n_per_class=N_PER_CLASS, seed=SEED):
    """Return a class-balanced subsample of (X, y)."""
    rng = np.random.default_rng(seed)
    idxs = []
    for cls in np.unique(y):
        pool = np.where(y == cls)[0]
        idxs.append(rng.choice(pool, min(n_per_class, len(pool)), replace=False))
    idx = np.concatenate(idxs)
    rng.shuffle(idx)
    return X[idx], y[idx]


def load_rt_iot(data_root="data"):
    """
    Load and preprocess RT-IoT2022.
    Returns (X_train, X_test, y_train, y_test, class_names, feat_mask).
    """
    csv_path = os.path.join(data_root, "RT_IOT", "RT_IOT2022.csv")
    df = pd.read_csv(csv_path)

    y_col = "Attack_type"
    y_raw = df[y_col].astype(str).values
    X_raw = df.drop(columns=[y_col, "Unnamed: 0"], errors="ignore")

    # Encode string columns
    for col in X_raw.select_dtypes("object").columns:
        X_raw[col] = LabelEncoder().fit_transform(X_raw[col].astype(str))

    X = X_raw.fillna(0).values.astype(np.float32)

    # Keep top-5 classes, label-encode
    le = LabelEncoder()
    y_enc = le.fit_transform(y_raw)
    class_names = list(le.classes_)

    # Stratified 2000/class balanced sample
    X, y_enc = stratified_subsample(X, y_enc, n_per_class=N_PER_CLASS)

    # Shuffle
    perm = np.random.permutation(len(X))
    X, y_enc = X[perm], y_enc[perm]

    # 80/20 split
    sc = StandardScaler()
    split = int(0.8 * len(X))
    X_tr = sc.fit_transform(X[:split]).astype(np.float32)
    X_te = sc.transform(X[split:]).astype(np.float32)
    y_tr, y_te = y_enc[:split].astype(np.int64), y_enc[split:].astype(np.int64)

    # Trim perturbability mask to actual feature count
    feat_mask = PERTURBABLE_IOT[:X_tr.shape[1]]

    print(f"  RT-IoT2022: {X_tr.shape[0]} train / {X_te.shape[0]} test  "
          f"| {X_tr.shape[1]} features  | {len(class_names)} classes")
    print(f"  Classes: {class_names}")
    return X_tr, X_te, y_tr, y_te, class_names, feat_mask


